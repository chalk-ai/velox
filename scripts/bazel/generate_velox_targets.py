def migrate() -> None:
    if LAYERS_FILE.exists():
        sys.exit(f"{LAYERS_FILE} already exists; migrate runs once")
    text = ROOT_BUILD.read_text()
    lines = text.splitlines(keepends=True)
    module = ast.parse(text)

    spans: list[tuple[int, int, str, str | None]] = []  # start, end, kind, name
    for stmt in module.body:
        if (
            isinstance(stmt, ast.Assign)
            and isinstance(stmt.targets[0], ast.Name)
            and stmt.targets[0].id in LAYER_VARIABLES
        ):
            spans.append((stmt.lineno, stmt.end_lineno, "var", stmt.targets[0].id))
        elif (
            isinstance(stmt, ast.Expr)
            and isinstance(stmt.value, ast.Call)
            and getattr(stmt.value.func, "id", None) == "cc_library"
        ):
            name = next(
                (
                    ast.literal_eval(k.value)
                    for k in stmt.value.keywords
                    if k.arg == "name"
                ),
                None,
            )
            if name in LAYER_NAMES:
                spans.append((stmt.lineno, stmt.end_lineno, "layer", name))
    found = {name for _, _, kind, name in spans if kind == "layer"}
    if found != set(LAYER_NAMES):
        sys.exit(f"expected layers {LAYER_NAMES}, found {sorted(found)}")

    # Extend each span upward over its attached comment block.
    extended = []
    for start, end, kind, name in sorted(spans):
        while start > 1 and lines[start - 2].lstrip().startswith("#"):
            start -= 1
        extended.append((start, end, kind, name))

    out = [
        '"""The core Velox layers, as data.\n\n'
        "Nothing in Bazel loads this file. scripts/bazel/generate_velox_targets.py\n"
        "reads it and writes bazel/velox_generated.bzl, which declares one target\n"
        "per header and source file plus an umbrella per layer. Edit the lists here\n"
        "and rerun the script.\n"
        '"""\n\n'
    ]
    order = []
    for start, end, kind, name in extended:
        block = "".join(lines[start - 1 : end])
        if kind == "layer":
            const = f"_{name.upper()}"
            block = re.sub(
                r"^cc_library\(", f"{const} = dict(", block, count=1, flags=re.M
            )
            order.append(const)
        out.append(block.rstrip("\n") + "\n\n")
    out.append("VELOX_LAYERS = [\n" + "".join(f"    {c},\n" for c in order) + "]\n")

    first_layer_start = min(s for s, _, kind, _ in extended if kind == "layer")
    removed = set()
    for start, end, _, _ in extended:
        removed.update(range(start, end + 1))
        # Drop one blank separator line after the block.
        if end < len(lines) and not lines[end].strip():
            removed.add(end + 1)
    new_lines = []
    for number, line in enumerate(lines, start=1):
        if number == first_layer_start:
            new_lines.append(
                "# The core layers (base, vector, engine, functions, velox) are declared\n"
                "# per file from bazel/velox_layers.bzl. Edit that file and run\n"
                "# scripts/bazel/generate_velox_targets.py generate.\n"
                "velox_generated_targets()\n\n"
            )
        if number not in removed:
            new_lines.append(line)
    new_text = "".join(new_lines)
    load_line = 'load("//bazel:velox_generated.bzl", "velox_generated_targets")\n'
    new_text = new_text.replace('load("@fbthrift//', load_line + 'load("@fbthrift//', 1)
    if load_line not in new_text:
        sys.exit("could not find where to add the load statement")

    LAYERS_FILE.parent.mkdir(exist_ok=True)
    LAYERS_FILE.write_text("".join(out))
    if not BAZEL_PACKAGE_BUILD.exists():
        BAZEL_PACKAGE_BUILD.write_text(
            "# Package for the Velox layer definitions and their generated targets.\n"
        )
    ROOT_BUILD.write_text(new_text)
    print(f"wrote {LAYERS_FILE.relative_to(REPO)}; updated BUILD.bazel")


