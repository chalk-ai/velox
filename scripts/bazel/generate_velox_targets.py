CMAKE_SKIP_DIR = re.compile(
    r"(^|/)(tests?|benchmarks?|fuzzer|experimental|examples|tool)(/|$)"
)
CMAKE_KEYWORDS = {"OBJECT", "STATIC", "SHARED", "INTERFACE", "PUBLIC", "PRIVATE"}


def cmake_commands(text: str):
    """Yields (command, args) with comments stripped and ${VAR} left in place."""
    text = re.sub(r"#\[\[.*?\]\]", "", text, flags=re.S)
    text = re.sub(r'#[^\n"]*', "", text)
    for match in re.finditer(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", text):
        depth, i = 1, match.end()
        while i < len(text) and depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        body = text[match.end() : i - 1]
        yield match.group(1).lower(), re.findall(r'"[^"]*"|[^\s"]+', body)


def cmake_files() -> dict[str, str]:
    """Maps each non-test file listed by Velox's CMake to its CMake library.

    Both branches of every if() are taken, so feature-gated files are included;
    the report says where they are so Chalk's choices can be checked against it.
    """
    files: dict[str, str] = {}
    for cmake in sorted((REPO / "velox").rglob("CMakeLists.txt")):
        rel_dir = cmake.parent.relative_to(REPO)
        if CMAKE_SKIP_DIR.search(str(rel_dir)):
            continue
        variables: dict[str, list[str]] = collections.defaultdict(list)

        def expand(arg: str) -> list[str]:
            arg = arg.strip('"')
            m = re.fullmatch(r"\$\{(\w+)\}", arg)
            if m:
                return list(variables.get(m.group(1), []))
            return [arg] if "$" not in arg else []

        for command, args in cmake_commands(cmake.read_text()):
            if command == "set" and args:
                variables[args[0]] = [v for a in args[1:] for v in expand(a)]
            elif command == "list" and len(args) > 2 and args[0] == "APPEND":
                variables[args[1]] += [v for a in args[2:] for v in expand(a)]
            elif command in ("velox_add_library", "velox_sources") and args:
                library = args[0]
                for arg in args[1:]:
                    for value in expand(arg):
                        if value in CMAKE_KEYWORDS or value == "HEADERS":
                            continue
                        if not re.search(r"\.(cpp|cc|c|h|hpp|inc)$", value):
                            continue
                        path = os.path.normpath(str(rel_dir / value))
                        if (REPO / path).is_file():
                            files.setdefault(path, library)
    return files


def cmake_report(verbose: bool) -> None:
    layers = load_layers()
    in_layers = {
        p
        for layer in layers
        for attr in ("srcs", "hdrs", "textual_hdrs")
        for p in layer.get(attr, [])
    }
    owned = set(in_layers)
    for path in [ROOT_BUILD] + sorted((REPO / "velox").rglob("BUILD.bazel")):
        rules, _ = parse_build_file(path)
        for rule in rules:
            pkg = f"{rule.package}/" if rule.package else ""
            for attr in ("srcs", "hdrs", "textual_hdrs"):
                owned.update(
                    pkg + f
                    for f in rule.attrs.get(attr, [])
                    if isinstance(f, str) and not f.startswith((":", "//", "@"))
                )
    cmake = cmake_files()

    def show(title: str, paths: list[str]) -> None:
        print(f"\n{title}: {len(paths)}")
        by_dir = collections.Counter(os.path.dirname(p) for p in paths)
        if verbose:
            for p in paths:
                print(f"    {p}  ({cmake.get(p, '-')})")
        else:
            for d, n in sorted(by_dir.items()):
                print(f"    {n:4}  {d}/")

    show(
        "In Velox CMake but in no Bazel target (new upstream files, or features Chalk leaves off)",
        sorted(set(cmake) - owned),
    )
    show(
        "In a layer but listed by no CMake library (Chalk-only, or removed upstream)",
        sorted(p for p in in_layers if p not in cmake),
    )
    missing = sorted(p for p in in_layers if not (REPO / p).is_file())
    show("In a layer but missing on disk (must be removed from the layer)", missing)


