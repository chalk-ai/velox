"""Generate fine-grained Bazel targets for Velox's core layers.

Velox's non-test sources are grouped into a few coarse layers (base, vector,
engine, functions, velox). Compiling a layer as one cc_library makes every TU's
cache key cover every header of the layer and of the layers below it, so any
header change invalidates most of Velox. This script keeps the layers as the
hand-maintained source of truth (bazel/velox_layers.bzl) and emits one target per
header and one per source file, with deps taken from each file's #includes
(bazel/velox_generated.bzl). The layer names stay as umbrella targets, so
consumers and linking are unchanged.

Run by hand after editing bazel/velox_layers.bzl or merging upstream:

    scripts/bazel/generate_velox_targets.py generate        # rewrite the .bzl
    scripts/bazel/generate_velox_targets.py generate --check # fail if stale
    scripts/bazel/generate_velox_targets.py cmake-report    # files to add/remove
    scripts/bazel/generate_velox_targets.py migrate         # one-time extraction

Velox's CMake per-library deps are not used: CMake builds Velox as one merged
library by default (VELOX_MONO_LIBRARY), so those deps are unenforced and cyclic.
"""

