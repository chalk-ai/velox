def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate", help="write bazel/velox_generated.bzl")
    gen.add_argument("--check", action="store_true", help="fail if the file is stale")
    gen.add_argument("--strict", action="store_true", help="treat warnings as errors")
    gen.add_argument("--verbose", action="store_true", help="list every warning")
    sub.add_parser("migrate", help="one-time: move the layers out of BUILD.bazel")
    report = sub.add_parser("cmake-report", help="compare layers with Velox's CMake")
    report.add_argument("--verbose", action="store_true", help="list every file")
    args = parser.parse_args()

    if args.command == "migrate":
        migrate()
    elif args.command == "cmake-report":
        cmake_report(args.verbose)
    else:
        generator = Generator(strict=args.strict)
        content = generator.build()
        generator.report_warnings(args.verbose)
        if args.check:
            current = GENERATED_FILE.read_text() if GENERATED_FILE.exists() else ""
            if current != content:
                sys.exit(f"{GENERATED_FILE.relative_to(REPO)} is stale; rerun generate")
            print("up to date")
            return
        GENERATED_FILE.write_text(content)
        n_targets = content.count("    cc_library(")
        print(f"wrote {GENERATED_FILE.relative_to(REPO)}: {n_targets} targets")


if __name__ == "__main__":
    main()
